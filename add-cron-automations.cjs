const cronJobs = `
// ── 1. AI Smart Insights — daily at 8am IST (2:30am UTC) ────
cron.schedule('30 2 * * *', async () => {
  try {
    console.log('[Cron] Running daily AI Smart Insights...');
    const tenants = await pool.query('SELECT DISTINCT tenant_id FROM users WHERE is_active=true').catch(()=>({rows:[]}));
    for (const row of tenants.rows) {
      try {
        // Generate executive summary
        const resp = await fetch(process.env.BACKEND_URL+'/api/ai/insights/generate', {
          method: 'POST',
          headers: {'Content-Type':'application/json','Authorization':'Bearer internal-'+row.tenant_id},
          body: JSON.stringify({insight_type:'executive_summary'})
        });
        if (resp.ok) console.log('[AI Insights] Generated for tenant', row.tenant_id);
      } catch(e) { console.error('[AI Insights] Error:', e); }
    }
  } catch(e) { console.error('[AI Insights Cron] Error:', e); }
});

// ── 2. Anomaly Detection — daily at 9am IST (3:30am UTC) ────
cron.schedule('30 3 * * *', async () => {
  try {
    console.log('[Cron] Running daily Anomaly Detection...');
    const tenants = await pool.query('SELECT DISTINCT tenant_id FROM users WHERE is_active=true').catch(()=>({rows:[]}));
    for (const row of tenants.rows) {
      try {
        const resp = await fetch(process.env.BACKEND_URL+'/api/ai/anomaly/detect', {
          method: 'POST',
          headers: {'Content-Type':'application/json','Authorization':'Bearer internal-'+row.tenant_id},
        });
        const result = await resp.json();
        if (result.anomalies?.length > 0) {
          console.log('[Anomaly] Found', result.anomalies.length, 'anomalies for tenant', row.tenant_id);
          // Email high/critical anomalies immediately
          const critical = result.anomalies.filter((a:any) => ['high','critical'].includes(a.severity));
          if (critical.length > 0) {
            const user = await pool.query('SELECT email FROM users WHERE tenant_id=$1 LIMIT 1',[row.tenant_id]).catch(()=>({rows:[]}));
            if (user.rows[0]?.email) {
              const { Resend } = await import('resend');
              const resend = new Resend(process.env.RESEND_API_KEY);
              await resend.emails.send({
                from: 'Deemona Anomaly Alerts <onboarding@resend.dev>',
                to: user.rows[0].email,
                subject: \`\u26a0\ufe0f \${critical.length} Financial Anomalies Detected — \${new Date().toLocaleDateString('en-IN')}\`,
                html: \`<html><body style="font-family:Arial;padding:20px;max-width:600px">
                  <h2 style="color:#dc2626">\u26a0\ufe0f Financial Anomaly Alert</h2>
                  <p><strong>\${critical.length} high/critical anomalies detected</strong> in your financial data.</p>
                  \${critical.map((a:any) => \`
                    <div style="background:#fef2f2;border-left:4px solid #dc2626;padding:12px;margin:10px 0;border-radius:4px">
                      <strong style="color:#dc2626">\${a.severity?.toUpperCase()}: \${a.metric}</strong><br>
                      <span style="color:#334155">\${a.description}</span><br>
                      <span style="color:#64748b;font-size:12px">\${a.ai_explanation||''}</span>
                    </div>
                  \`).join('')}
                  <p style="color:#64748b;font-size:12px">Auto-generated by Deemona AI Finance OS — Anomaly Detection</p>
                </body></html>\`
              }).catch(()=>{});
            }
          }
        }
      } catch(e) { console.error('[Anomaly] Error for tenant', row.tenant_id, e); }
    }
  } catch(e) { console.error('[Anomaly Cron] Error:', e); }
});

// ── 3. Balance Sheet Email — every Monday at 9am IST (3:30am UTC) ────
cron.schedule('30 3 * * 1', async () => {
  try {
    console.log('[Cron] Running weekly Balance Sheet email...');
    const tenants = await pool.query('SELECT DISTINCT u.tenant_id, u.email FROM users u WHERE u.is_active=true').catch(()=>({rows:[]}));
    for (const row of tenants.rows) {
      try {
        const resp = await fetch(process.env.BACKEND_URL+'/api/ai/balance-sheet', {
          headers: {'Authorization':'Bearer internal-'+row.tenant_id}
        });
        const bs = await resp.json();
        if (!bs.assets) continue;
        const fmt = (n:any) => { const v=parseFloat(n||0); if(v>=10000000) return '\u20b9'+(v/10000000).toFixed(2)+'Cr'; if(v>=100000) return '\u20b9'+(v/100000).toFixed(2)+'L'; return '\u20b9'+v.toFixed(0); };
        const { Resend } = await import('resend');
        const resend = new Resend(process.env.RESEND_API_KEY);
        await resend.emails.send({
          from: 'Deemona Finance OS <onboarding@resend.dev>',
          to: row.email,
          subject: \`\u2696\ufe0f Weekly Balance Sheet — \${new Date().toLocaleDateString('en-IN',{day:'2-digit',month:'short',year:'numeric'})}\`,
          html: \`<html><body style="font-family:Arial;padding:20px;max-width:600px">
            <h2 style="color:#1d4ed8">\u2696\ufe0f Weekly Balance Sheet Summary</h2>
            <p>As of \${bs.asOfDate}</p>
            <table style="width:100%;border-collapse:collapse;font-size:13px">
              <tr style="background:#f8faff"><td style="padding:10px;font-weight:700;color:#0f172a" colspan="2">ASSETS</td></tr>
              <tr><td style="padding:8px 10px;color:#64748b">Cash & Bank</td><td style="padding:8px 10px;text-align:right;font-weight:700;color:#059669">\${fmt(bs.assets.current.cash)}</td></tr>
              <tr><td style="padding:8px 10px;color:#64748b">Accounts Receivable</td><td style="padding:8px 10px;text-align:right;font-weight:700;color:#059669">\${fmt(bs.assets.current.accountsReceivable)}</td></tr>
              <tr><td style="padding:8px 10px;color:#64748b">Inventory</td><td style="padding:8px 10px;text-align:right;color:#059669">\${fmt(bs.assets.current.inventory)}</td></tr>
              <tr><td style="padding:8px 10px;color:#64748b">Fixed Assets</td><td style="padding:8px 10px;text-align:right;color:#1d4ed8">\${fmt(bs.assets.fixed.total)}</td></tr>
              <tr style="background:#eff6ff"><td style="padding:10px;font-weight:800;color:#1d4ed8">TOTAL ASSETS</td><td style="padding:10px;text-align:right;font-weight:900;color:#1d4ed8;font-size:16px">\${fmt(bs.assets.total)}</td></tr>
              <tr style="background:#f8faff"><td style="padding:10px;font-weight:700;color:#0f172a" colspan="2">LIABILITIES & EQUITY</td></tr>
              <tr><td style="padding:8px 10px;color:#64748b">Accounts Payable</td><td style="padding:8px 10px;text-align:right;color:#dc2626">\${fmt(bs.liabilities.current.accountsPayable)}</td></tr>
              <tr><td style="padding:8px 10px;color:#64748b">Long-term Loans</td><td style="padding:8px 10px;text-align:right;color:#dc2626">\${fmt(bs.liabilities.longTerm.loans)}</td></tr>
              <tr style="background:#fef2f2"><td style="padding:10px;font-weight:800;color:#dc2626">TOTAL LIABILITIES</td><td style="padding:10px;text-align:right;font-weight:900;color:#dc2626">\${fmt(bs.liabilities.total)}</td></tr>
              <tr style="background:#f0fdf4"><td style="padding:10px;font-weight:800;color:#059669">SHAREHOLDERS EQUITY</td><td style="padding:10px;text-align:right;font-weight:900;color:#059669;font-size:16px">\${fmt(bs.equity.total)}</td></tr>
            </table>
            <div style="margin-top:16px;padding:12px;background:#f8faff;border-radius:8px;font-size:12px">
              <strong>Key Ratios:</strong> Current Ratio: \${bs.ratios.currentRatio}x &nbsp;|&nbsp; Debt/Equity: \${bs.ratios.debtToEquity}x &nbsp;|&nbsp; Asset Turnover: \${bs.ratios.assetTurnover}x
            </div>
            <p style="color:#64748b;font-size:12px;margin-top:16px">Auto-generated every Monday by Deemona AI Finance OS</p>
          </body></html>\`
        }).catch(()=>{});
        console.log('[Balance Sheet] Emailed to', row.email);
      } catch(e) { console.error('[Balance Sheet] Error:', e); }
    }
  } catch(e) { console.error('[Balance Sheet Cron] Error:', e); }
});

// ── 4. Filing Reports — 1st of every month at 10am IST (4:30am UTC) ────
cron.schedule('30 4 1 * *', async () => {
  try {
    console.log('[Cron] Running monthly Filing Reports...');
    const tenants = await pool.query('SELECT DISTINCT tenant_id FROM users WHERE is_active=true').catch(()=>({rows:[]}));
    const period = new Date().toLocaleDateString('en-IN',{month:'long',year:'numeric'});
    const filingTypes = ['GST_GSTR3B','TDS_26Q'];
    for (const row of tenants.rows) {
      for (const filingType of filingTypes) {
        try {
          const resp = await fetch(process.env.BACKEND_URL+'/api/ai/filing/generate', {
            method: 'POST',
            headers: {'Content-Type':'application/json','Authorization':'Bearer internal-'+row.tenant_id},
            body: JSON.stringify({filing_type:filingType, period})
          });
          if (resp.ok) console.log('[Filing] Generated', filingType, 'for tenant', row.tenant_id);
        } catch(e) { console.error('[Filing] Error:', e); }
      }
    }
  } catch(e) { console.error('[Filing Cron] Error:', e); }
});

`;

